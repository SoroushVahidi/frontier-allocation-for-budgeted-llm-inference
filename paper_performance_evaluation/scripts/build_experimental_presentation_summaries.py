#!/usr/bin/env python3
"""Build paper-only experimental presentation tables from released aggregate records.

This script reads the compact public audit under outputs/ and writes LaTeX snippets under
paper_performance_evaluation/tables/. It performs no provider calls and does not read unavailable
historical per-example completions.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path


SCRIPT_DIR = Path(__file__).resolve().parent
PAPER_DIR = SCRIPT_DIR.parent
REPO_ROOT = PAPER_DIR.parent
AUDIT_ROOT = REPO_ROOT / "outputs" / "final_4x4_matrix_conclusive_audit_20260717T223631Z"
TABLE_DIR = PAPER_DIR / "tables"


def read_csv(name: str) -> list[dict[str, str]]:
    with (AUDIT_ROOT / name).open(newline="") as handle:
        return list(csv.DictReader(handle))


def pct(num: int, den: int) -> str:
    return f"{(100.0 * num / den):.1f}\\%" if den else "--"


def fix2_stats(rows: list[dict[str, str]]) -> dict[str, dict[str, int | str]]:
    scopes = {
        "All completed cells": lambda r: True,
        "Excluding development-adjacent Cohere GSM8K": (
            lambda r: not (r["provider"] == "cohere" and r["dataset"] == "openai/gsm8k")
        ),
        "Azure GSM8K + MATH-500": (
            lambda r: r["provider"] == "azure_openai"
            and r["dataset"] in {"openai/gsm8k", "HuggingFaceH4/MATH-500"}
        ),
        "Development-adjacent Cohere GSM8K": (
            lambda r: r["provider"] == "cohere" and r["dataset"] == "openai/gsm8k"
        ),
    }
    out: dict[str, dict[str, int | str]] = {}
    for label, filt in scopes.items():
        scoped = [r for r in rows if filt(r)]
        triggers = sum(int(r["fix2_trigger_count"]) for r in scoped)
        rescues = sum(int(r["fix2_rescues"]) for r in scoped)
        regressions = sum(int(r["fix2_regressions"]) for r in scoped)
        neutral = sum(int(r["fix2_neutral_changes"]) for r in scoped)
        out[label] = {
            "cells": len(scoped),
            "triggers": triggers,
            "rescues": rescues,
            "regressions": regressions,
            "neutral": neutral,
            "net": rescues - regressions,
            "rescue_rate": pct(rescues, triggers),
            "regression_rate": pct(regressions, triggers),
        }
    return out


def source_path_status() -> dict[str, int]:
    matrix = read_csv("final_4x4_matrix.csv")
    source_map = json.loads((AUDIT_ROOT / "source_of_truth_map.json").read_text())
    paths: set[str] = set()
    for row in matrix:
        for path in row.get("source_files", "").split(";"):
            if path.strip():
                paths.add(path.strip())
    for entry in source_map.values():
        for path in entry.get("raw_source_files", []):
            paths.add(path)
        if entry.get("raw_unsanitized_path"):
            paths.add(entry["raw_unsanitized_path"])
        if entry.get("evidence"):
            paths.add(entry["evidence"])
    present = sum(1 for path in paths if (REPO_ROOT / path).exists())
    return {"referenced": len(paths), "present": present, "missing": len(paths) - present}


def write_accounting_status_table() -> None:
    text = r"""% Generated by scripts/build_experimental_presentation_summaries.py.
\begin{tabularx}{\textwidth}{@{}>{\raggedright\arraybackslash}p{3.0cm}>{\raggedright\arraybackslash}p{5.8cm}Y@{}}
\toprule
Field & Accounting status & Interpretation \\
\midrule
Nominal budget & Fixed at $B{=}6$ for each Class~A policy; not a realized resource. & Equalizes logical opportunity only. \\
Successful calls & Adapter calls observed; Frontier calls reconstructed from stored outer calls plus maturity. & Exact after reconstruction; mean Frontier calls change from $2.78$ to $5.38$. \\
Tokens and USD & Adapter token fields/pricing are complete; Frontier challenger-phase tokens are absent. & Frontier token and dollar ratios are lower bounds; Figure~\ref{fig:tradeoff} is not a Pareto frontier. \\
Latency & Reported as a separate Class~A realized-resource field. & Not collapsed with accuracy, tokens, or dollars. \\
Retries & Provider/harness retry records are partial; paid-retry accounting is incomplete. & Retry totals are not used as complete cost claims. \\
\bottomrule
\end{tabularx}
"""
    (TABLE_DIR / "table9_accounting_status.tex").write_text(text)


def main() -> None:
    selector_rows = read_csv("selector_behavior_by_cell.csv")
    stats = fix2_stats(selector_rows)
    source_status = source_path_status()
    write_accounting_status_table()
    print(json.dumps({"fix2": stats, "source_path_status": source_status}, indent=2))


if __name__ == "__main__":
    main()
